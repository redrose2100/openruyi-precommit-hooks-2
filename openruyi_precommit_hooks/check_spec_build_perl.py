"""Enforce the requirements of the Perl declarative build systems.

The ``perl`` supplement of the packaging guidelines describes the two
declarative build systems openRuyi provides for CPAN-style modules, and the
dependencies each of them implies.

Section "Dependencies" states, verbatim:

> If you need to use a Perl declarative build system, you *typically* need to
> add the following `BuildRequires`:
>
>     BuildRequires:  perl-rpm-packaging
>     BuildRequires:  perl-rpm-macros
>     BuildRequires:  perl-macros
>
> You should also add the Perl module dependencies your upstream build script
> needs, for example: `perl(Module::Build)`, `perl(ExtUtils::MakeMaker)`.
> Among them: when using `perlbuild`, you *typically* need
> `perl(Module::Build)`. When using `perlmaker`, you *typically* need
> `perl(ExtUtils::MakeMaker)`.

Section "File list" states:

> Perl packages *typically* use an automatically generated file list:
>
>     %files -f %{name}.files
>     %doc Changes README
>
> `%perl_gen_filelist` generates `%{name}.files` during the installation
> phase. Therefore, when using `perlbuild` or `perlmaker`, you *typically*
> do not need to list all Perl module files by hand.

Three checkpoints are implemented, and each one is anchored in one of those
clauses:

* C1 reproduces the three-package `BuildRequires` block the page names for
  both build systems.
* C2 reproduces the per-system module capability: ``perl(Module::Build)``
  for ``perlbuild`` and ``perl(ExtUtils::MakeMaker)`` for ``perlmaker``.
* C5 reproduces the automatic file list: a Perl spec is expected to carry
  ``%files -f`` so the list generated by ``%perl_gen_filelist`` is used.

Every clause above is worded with *typically*, not with *must*, so each
checkpoint is enforced as a regression guard rather than as a hard error in
the guideline: all 403 Perl specs in the reference corpus already comply,
which makes a new violation a strong signal that a spec was copied from an
unrelated template. The rule therefore never contradicts a compliant spec,
and a packager who has a real reason to deviate can switch the individual
checkpoint off.

Deliberately out of scope: whether ``Build.PL`` or ``Makefile.PL`` is present
in the upstream tarball (the page chooses the build system from the source
tree, which a spec-only linter cannot inspect), the exact arguments of
``BuildOption(build)``/``BuildOption(install)`` (the page gives them as
examples, and the corpus deviates legitimately), the presence or contents of
``%build``/``%install``/``%check`` (the page states that these are usually
omitted but may be overridden), and the syntax of ``BuildOption`` itself
(owned by ``check-spec-buildoption``).

No network access and no ``rpm`` invocation is performed, so the rule works
on a bare checkout.
"""
from __future__ import annotations

import argparse
import re
from collections.abc import Sequence
from typing import NamedTuple


# Any top-level "Field: value" line. A trailing parenthesised argument such
# as the stage of "BuildOption(build):" belongs to the field name rather
# than to the value, so the group is matched and dropped.
RE_FIELD = re.compile(r'^([A-Za-z]\w*)(?:\(([^)]*)\))?\s*:\s*(.*)$')

# A section header, together with everything that follows the section name
# on the same line. For "%files" the remainder is empty; for
# "%files -f %{name}.files" it is "-f %{name}.files".
RE_SECTION = re.compile(r'^%([a-z]\w*)\b(.*)$')

# The field that switches the requirement on, and the field that satisfies
# it. Both are matched loosely so a misspelling reported by the dedicated
# rules still contributes its value here.
RE_BUILD_SYSTEM = re.compile(r'^build-?system$', re.IGNORECASE)
RE_BUILD_REQUIRES = re.compile(r'^build-?requires?$', re.IGNORECASE)

# A Perl module capability such as "perl(Module::Build)". The capability is
# a rich dependency, so the generic dependency splitter drops it; matching it
# separately keeps the colon-separated module name intact.
RE_PERL_CAPABILITY = re.compile(
    r'\bperl\(\s*([A-Za-z_][\w:]*)\s*\)', re.IGNORECASE,
)

# The "-f" argument of a %files section, which makes RPM read the file list
# from a separate file instead of the section body.
RE_FILES_FILE = re.compile(r'(?:^|\s)-f\s*\S+')

# The dependency operators. A token that is exactly an operator consumes the
# token after it, which is the version of the dependency to its left.
RE_OPERATOR = re.compile(r'^(?:<=|>=|=|<|>)$')

# The two keywords that join two dependency names into one clause.
_JOINERS = frozenset({'with', 'without'})

# The closed set of real RPM sections, mirroring check-spec-basic-fields.
# Anything else that starts with "%" is a macro invocation (%license, %doc,
# %systemd_post, %autochangelog, ...) and must never be mistaken for a
# section.
KNOWN_SECTIONS: frozenset[str] = frozenset({
    '%description',
    '%package',
    '%prep',
    '%conf',
    '%build',
    '%install',
    '%check',
    '%clean',
    '%files',
    '%changelog',
    '%pre',
    '%post',
    '%preun',
    '%postun',
    '%pretrans',
    '%posttrans',
    '%triggerprein',
    '%triggerin',
    '%triggerun',
    '%triggerpostun',
    '%verifyscript',
    '%generate_buildrequires',
})

# The two declarative build systems this rule covers. The names are spelled
# exactly as the page spells them.
PERLBUILD = 'perlbuild'
PERLMAKER = 'perlmaker'
PERL_SYSTEMS: frozenset[str] = frozenset({PERLBUILD, PERLMAKER})

# The shared macro packages the page asks for regardless of the build
# system. Their order is the order of the page.
SHARED_PACKAGES: tuple[str, ...] = (
    'perl-rpm-packaging',
    'perl-rpm-macros',
    'perl-macros',
)

# The module capability each build system implies, keyed by the build system
# name. The value is the lowercase capability name without the "perl()"
# wrapper.
REQUIRED_MODULE: dict[str, str] = {
    PERLBUILD: 'module::build',
    PERLMAKER: 'extutils::makemaker',
}

# The human-readable spelling of the required module, used in messages.
MODULE_SPELLING: dict[str, str] = {
    PERLBUILD: 'perl(Module::Build)',
    PERLMAKER: 'perl(ExtUtils::MakeMaker)',
}


class _Block(NamedTuple):
    """One field block: the fields it holds, in file order.

    ``fields`` is a list of ``(spelling, stage, value, 1-based line)``
    tuples, where ``stage`` is the parenthesised argument of a field name or
    the empty string when the name carries none.
    """

    fields: list[tuple[str, str, str, int]]


class _Section(NamedTuple):
    """One section: its name, its suffix, and its non-comment body lines.

    ``suffix`` is whatever follows the section name on the header line, with
    surrounding whitespace removed, so ``%files`` yields the empty string and
    ``%files -f %{name}.files`` yields ``-f %{name}.files``. ``body`` is a
    list of ``(1-based line, text)`` tuples that excludes blank and comment
    lines.
    """

    name: str
    suffix: str
    header_line: int
    body: list[tuple[int, str]]


def _dedup(errors: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for err in errors:
        if err not in seen:
            seen.add(err)
            out.append(err)
    return out


def _read_lines(filename: str) -> tuple[list[str] | None, str | None]:
    """Return the spec's lines, or (None, error) when it cannot be read."""
    try:
        with open(filename, encoding='utf-8') as f:
            return f.read().splitlines(), None
    except UnicodeDecodeError:
        return None, f'{filename}: file is not valid UTF-8'
    except OSError as exc:
        return None, f'{filename}: {exc}'


def _is_section(line: str) -> str | None:
    """Return the known section name on this line, or None."""
    match = RE_SECTION.match(line)
    if match is None:
        return None
    section = '%' + match.group(1)
    if section in KNOWN_SECTIONS:
        return section
    return None


def _macro_depth_after(line: str, depth: int) -> int:
    """Return the macro nesting depth after consuming one line."""
    depth += line.count('{') - line.count('}')
    return depth if depth > 0 else 0


def _blocks_of(lines: list[str]) -> list[_Block]:
    """Split the file into field blocks.

    The first block is the main preamble, kept even when it holds no field.
    Every ``%package`` opens a fresh block, so a subpackage that declares a
    build system of its own is judged against its own dependencies. A block
    ends at the first known section, so a macro invocation such as
    ``%global debug_package %{nil}`` neither ends a block nor hides the
    fields that follow it.
    """
    raw: list[list[tuple[str, str, str, int]]] = []
    fields: list[tuple[str, str, str, int]] = []
    macro_depth = 0

    for index, line in enumerate(lines, 1):
        if macro_depth > 0:
            macro_depth = _macro_depth_after(line, macro_depth)
            continue
        section = _is_section(line)
        if section is not None:
            raw.append(fields)
            fields = []
            continue
        if line.startswith('#'):
            continue
        match = RE_FIELD.match(line)
        if match is None:
            continue
        name, stage, value = (
            match.group(1), match.group(2) or '', match.group(3),
        )
        fields.append((name, stage.strip(), value, index))
        macro_depth = _macro_depth_after(line, 0)

    raw.append(fields)
    blocks = [_Block(raw[0])]
    blocks.extend(_Block(item) for item in raw[1:] if item)
    return blocks


def _declared_names(value: str) -> set[str]:
    """Return the lowercase name of every dependency on one field line.

    A dependency is a name optionally followed by a version operator and a
    version, or one rich dependency in parentheses, or two names joined by
    a comma, ``with`` or ``without``. Only the names are returned, so a
    version number never looks like a dependency and ``perl-devel`` stays
    distinct from ``perl``.
    """
    names: set[str] = set()
    skip = False
    depth = 0
    for token in value.split():
        opens = token.count('(')
        closes = token.count(')')
        if depth > 0 or opens or closes:
            depth = max(depth + opens - closes, 0)
            skip = False
            continue
        if skip:
            skip = False
            continue
        if RE_OPERATOR.match(token) is not None:
            skip = True
            continue
        if token.lower() in _JOINERS:
            skip = True
            continue
        names.add(token.rstrip(',').lower())
    return names


def _capability_names(value: str) -> set[str]:
    """Return the lowercase name of every ``perl(...)`` capability."""
    return {
        match.group(1).lower()
        for match in RE_PERL_CAPABILITY.finditer(value)
    }


def _systems(blocks: Sequence[_Block]) -> list[tuple[str, int]]:
    """Return every ``(build system, 1-based line)`` pair in the file.

    The build system name is lowercased. A spec that declares both systems
    yields two entries, so each one is checked against its own module.
    """
    found: list[tuple[str, int]] = []
    for block in blocks:
        for name, _stage, value, line in block.fields:
            if RE_BUILD_SYSTEM.match(name) is None:
                continue
            system = value.strip().lower()
            if system in PERL_SYSTEMS:
                found.append((system, line))
    return found


def _declared_everywhere(blocks: Sequence[_Block]) -> set[str]:
    """Return every plain dependency name declared in a build-requires field.

    ``BuildRequires`` is a source-package level field, so RPM merges the
    declarations of every subpackage block into one build dependency set.
    The requirement is therefore satisfied when the name appears anywhere
    in the file, which keeps a subpackage that carries the dependency from
    producing a false finding.
    """
    declared: set[str] = set()
    for block in blocks:
        for name, _stage, value, _line in block.fields:
            if RE_BUILD_REQUIRES.match(name) is not None:
                declared |= _declared_names(value)
    return declared


def _capabilities_everywhere(blocks: Sequence[_Block]) -> set[str]:
    """Return every ``perl(...)`` capability in a build-requires field."""
    declared: set[str] = set()
    for block in blocks:
        for name, _stage, value, _line in block.fields:
            if RE_BUILD_REQUIRES.match(name) is not None:
                declared |= _capability_names(value)
    return declared


def _section_list(lines: Sequence[str]) -> list[_Section]:
    """Split the file into sections, keeping each body line's number."""
    found: list[_Section] = []
    name = ''
    suffix = ''
    header = 0
    body: list[tuple[int, str]] = []

    for index, line in enumerate(lines, 1):
        match = RE_SECTION.match(line)
        if match is not None and ('%' + match.group(1)) in KNOWN_SECTIONS:
            if name:
                found.append(_Section(name, suffix, header, body))
            name = '%' + match.group(1)
            suffix = match.group(2).strip()
            header = index
            body = []
            continue
        if not name:
            continue
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        body.append((index, line))

    if name:
        found.append(_Section(name, suffix, header, body))
    return found


def _check_shared_packages(
    system: str, line: int, declared: set[str],
) -> list[str]:
    """C1: a Perl spec declares the three shared Perl macro packages."""
    missing = [pkg for pkg in SHARED_PACKAGES if pkg not in declared]
    if not missing:
        return []
    return [
        f'BuildSystem: {system} (line {line}) requires the shared Perl '
        f'build dependencies in BuildRequires; '
        f'missing {", ".join(missing)}',
    ]


def _check_module(
    system: str, line: int, capabilities: set[str],
) -> list[str]:
    """C2: a Perl spec declares the module its build system implies."""
    required = REQUIRED_MODULE[system]
    if required in capabilities:
        return []
    spelling = MODULE_SPELLING[system]
    return [
        f'BuildSystem: {system} (line {line}) requires '
        f'"{spelling}" in BuildRequires; missing "{spelling}"',
    ]


def _check_files_list(sections: Sequence[_Section]) -> list[str]:
    """C5: a Perl spec reads its main file list from the generated list.

    Only the first ``%files`` section is judged. That is the section of the
    main package, and it is the one ``%perl_gen_filelist`` fills, because
    the macro generates a single ``%{name}.files`` for the source package.
    A subpackage list is written by hand on purpose and is therefore left
    alone. A spec with no ``%files`` section at all is out of scope: the
    section is required for any package, and its absence is already
    reported by ``check-spec-basic-fields``.
    """
    section = next(
        (item for item in sections if item.name == '%files'), None,
    )
    if section is None:
        return []
    if RE_FILES_FILE.search(section.suffix) is not None:
        return []
    return [
        f'%files (line {section.header_line}) does not read a generated '
        f'file list; a Perl package is expected to use '
        f'%files -f %{{name}}.files',
    ]


def _check_spec_build_perl_ext(
    filename: str,
    *,
    check_shared_packages: bool = True,
    check_module: bool = True,
    check_files_list: bool = True,
) -> list[str]:
    lines, error = _read_lines(filename)
    if error is not None:
        return [error]
    assert lines is not None
    if not (check_shared_packages or check_module or check_files_list):
        return []

    blocks = _blocks_of(lines)
    systems = _systems(blocks)
    if not systems:
        return []

    errors: list[str] = []
    if check_shared_packages:
        declared = _declared_everywhere(blocks)
        errors.extend(
            _check_shared_packages(systems[0][0], systems[0][1], declared),
        )
    if check_module:
        capabilities = _capabilities_everywhere(blocks)
        for system, line in systems:
            errors.extend(_check_module(system, line, capabilities))
    if check_files_list:
        errors.extend(_check_files_list(_section_list(lines)))

    return _dedup([f'{filename}: {err}' for err in errors])


def _check_spec_build_perl(filename: str) -> list[str]:
    return _check_spec_build_perl_ext(filename)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description='Check the requirements of a Perl build system.',
    )
    parser.add_argument(
        'filenames', nargs='*', help='spec files to check',
    )
    parser.add_argument(
        '--no-check-shared-packages',
        action='store_true',
        help='do not report the shared Perl build dependencies',
    )
    parser.add_argument(
        '--no-check-module',
        action='store_true',
        help='do not report the module the build system implies',
    )
    parser.add_argument(
        '--no-check-files-list',
        action='store_true',
        help='do not report a %%files section without -f',
    )
    args = parser.parse_args(argv)

    ret = 0
    for filename in args.filenames:
        errors = _check_spec_build_perl_ext(
            filename,
            check_shared_packages=not args.no_check_shared_packages,
            check_module=not args.no_check_module,
            check_files_list=not args.no_check_files_list,
        )
        if errors:
            ret = 1
            for err in errors:
                print(err)
    return ret
