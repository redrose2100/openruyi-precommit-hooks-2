"""Enforce the requirements of the meson declarative build system.

The ``meson`` supplement of the packaging guidelines describes how a spec
opts into the declarative meson build system, which dependency the choice
implies, and where the meson option arguments belong once the spec stops
driving ``%meson`` by hand.

Section "Dependencies" states:

> To use the `meson` build system, add the following `BuildRequires`:
>
>     BuildRequires:  meson

The worked example of the page rewrites a hand-written ``%build`` into the
declarative form. The original section is::

    %build
    %meson -Dman=enabled -Dcompat-symlink=true -Dwtmpdbd=enabled
    %meson_build

and the page says, verbatim:

> After switching to the declarative `meson` build system, because the build
> process now features a dedicated configuration phase (`%conf`), you must
> move the option arguments to the corresponding section

The rewritten form is three ``BuildOption(conf)`` lines. The page then says
of the same example:

> Since `%meson_build` does not take any additional arguments here, your
> configuration requires no `BuildOption(build)` entries, and you do not
> need a separate `%build` section.

and, for the install phase:

> since `%meson_install` does not take any additional arguments in the
> current installation scenario, you do not need to add
> `BuildOption(install)`. Instead, move any commands that follow the
> `%meson_install` macro to the `%install -a` section as needed.

Three checkpoints are implemented, and each one is anchored in one of those
clauses:

* C1 is MUST level ("add the following BuildRequires") and reproduces the
  single dependency the page names.
* C2 follows the "you must move the option arguments" sentence: a meson
  ``-Dname=value`` option is a configuration-phase argument, so it belongs in
  ``BuildOption(conf)`` and nowhere else.
* C3 follows the "you do not need a separate %build section" sentence: the
  declarative system supplies ``%build`` and ``%install`` itself, so a plain
  section that carries its own statements is a hand-written step that the
  ``-a`` form is meant to replace.

Deliberately out of scope: whether a spec that calls ``%meson`` must declare
``BuildSystem: meson`` (the page only recommends the field, and the one spec
in the corpus that calls ``%meson`` without it does so on purpose, because
the Python helpers it needs are only generated by the ``pyproject`` build
system), the syntax of ``BuildOption`` itself (owned by
``check-spec-buildoption``), and every dependency question beyond the single
name above (owned by ``check-spec-buildrequires``).

No network access and no ``rpm`` invocation is performed, so the rule works
on a bare checkout.
"""
from __future__ import annotations

import argparse
import re
from collections.abc import Sequence
from typing import NamedTuple


# Any top-level "Field: value" line. A trailing parenthesised argument such
# as the stage of "BuildOption(build):" belongs to the field name rather
# than to the value, so the group is matched and dropped.
RE_FIELD = re.compile(r'^([A-Za-z]\w*)(?:\(([^)]*)\))?\s*:\s*(.*)$')

# A section header, together with everything that follows the section name
# on the same line. For "%build" the remainder is empty; for "%build -a" it
# is "-a". The remainder decides whether the section is the one the build
# system supplies or a user-appended one.
RE_SECTION = re.compile(r'^%([a-z]\w*)\b(.*)$')

# The field that switches the requirement on, and the field that satisfies
# it. Both are matched loosely so a misspelling reported by the dedicated
# rules still contributes its value here.
RE_BUILD_SYSTEM = re.compile(r'^build-?system$', re.IGNORECASE)
RE_BUILD_REQUIRES = re.compile(r'^build-?requires?$', re.IGNORECASE)
RE_BUILD_OPTION = re.compile(r'^build-?option$', re.IGNORECASE)

# A meson option argument: "-D" followed by a name, an equals sign, and the
# value. Meson rejects a "-D" without a value, so requiring the equals sign
# keeps an unrelated flag such as "install -Dpm0644" out of the match.
RE_MESON_OPTION = re.compile(r'(?:^|\s)(-D[A-Za-z_][\w-]*=\S*)')

# The dependency operators. A token that is exactly an operator consumes the
# token after it, which is the version of the dependency to its left.
RE_OPERATOR = re.compile(r'^(?:<=|>=|=|<|>)$')

# The two keywords that join two dependency names into one clause.
_JOINERS = frozenset({'with', 'without'})

# The closed set of real RPM sections, mirroring check-spec-basic-fields.
# Anything else that starts with "%" is a macro invocation (%license, %doc,
# %systemd_post, %autochangelog, ...) and must never be mistaken for a
# section.
KNOWN_SECTIONS: frozenset[str] = frozenset({
    '%description',
    '%package',
    '%prep',
    '%conf',
    '%build',
    '%install',
    '%check',
    '%clean',
    '%files',
    '%changelog',
    '%pre',
    '%post',
    '%preun',
    '%postun',
    '%pretrans',
    '%posttrans',
    '%triggerprein',
    '%triggerin',
    '%triggerun',
    '%triggerpostun',
    '%verifyscript',
    '%generate_buildrequires',
})

# The build system this rule covers, and the dependency the page names for
# it. The name is spelled exactly as the page spells it.
MESON = 'meson'
REQUIRED_PACKAGE = 'meson'

# The stage of the BuildOption field that holds the configuration-phase
# arguments, which is where the page moves the computed options.
CONF_STAGE = 'conf'

# The sections the declarative system supplies itself, and whose plain form
# therefore must not carry statements of its own.
MANAGED_SECTIONS: tuple[str, ...] = ('%build', '%install')


class _Block(NamedTuple):
    """One field block: the fields it holds, in file order.

    ``fields`` is a list of ``(spelling, stage, value, 1-based line)``
    tuples, where ``stage`` is the parenthesised argument of a field name or
    the empty string when the name carries none.
    """

    fields: list[tuple[str, str, str, int]]


class _Section(NamedTuple):
    """One section: its name, its suffix, and its non-comment body lines.

    ``suffix`` is whatever follows the section name on the header line, with
    surrounding whitespace removed, so ``%build`` yields the empty string and
    ``%build -a`` yields ``-a``. ``body`` is a list of
    ``(1-based line, text)`` tuples that excludes blank and comment lines.
    """

    name: str
    suffix: str
    header_line: int
    body: list[tuple[int, str]]


def _dedup(errors: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for err in errors:
        if err not in seen:
            seen.add(err)
            out.append(err)
    return out


def _read_lines(filename: str) -> tuple[list[str] | None, str | None]:
    """Return the spec's lines, or (None, error) when it cannot be read."""
    try:
        with open(filename, encoding='utf-8') as f:
            return f.read().splitlines(), None
    except UnicodeDecodeError:
        return None, f'{filename}: file is not valid UTF-8'
    except OSError as exc:
        return None, f'{filename}: {exc}'


def _is_section(line: str) -> str | None:
    """Return the known section name on this line, or None."""
    match = RE_SECTION.match(line)
    if match is None:
        return None
    section = '%' + match.group(1)
    if section in KNOWN_SECTIONS:
        return section
    return None


def _macro_depth_after(line: str, depth: int) -> int:
    """Return the macro nesting depth after consuming one line."""
    depth += line.count('{') - line.count('}')
    return depth if depth > 0 else 0


def _blocks_of(lines: list[str]) -> list[_Block]:
    """Split the file into field blocks.

    The first block is the main preamble, kept even when it holds no field.
    Every ``%package`` opens a fresh block, so a subpackage that declares a
    build system of its own is judged against its own dependencies. A block
    ends at the first known section, so a macro invocation such as
    ``%global debug_package %{nil}`` neither ends a block nor hides the
    fields that follow it.
    """
    raw: list[list[tuple[str, str, str, int]]] = []
    fields: list[tuple[str, str, str, int]] = []
    macro_depth = 0

    for index, line in enumerate(lines, 1):
        if macro_depth > 0:
            macro_depth = _macro_depth_after(line, macro_depth)
            continue
        section = _is_section(line)
        if section is not None:
            raw.append(fields)
            fields = []
            continue
        if line.startswith('#'):
            continue
        match = RE_FIELD.match(line)
        if match is None:
            continue
        name, stage, value = (
            match.group(1), match.group(2) or '', match.group(3),
        )
        fields.append((name, stage.strip(), value, index))
        macro_depth = _macro_depth_after(line, 0)

    raw.append(fields)
    blocks = [_Block(raw[0])]
    blocks.extend(_Block(item) for item in raw[1:] if item)
    return blocks


def _declared_names(value: str) -> set[str]:
    """Return the lowercase name of every dependency on one field line.

    A dependency is a name optionally followed by a version operator and a
    version, or one rich dependency in parentheses, or two names joined by
    a comma, ``with`` or ``without``. Only the names are returned, so a
    version number never looks like a dependency and ``meson-python`` stays
    distinct from ``meson``.
    """
    names: set[str] = set()
    skip = False
    depth = 0
    for token in value.split():
        opens = token.count('(')
        closes = token.count(')')
        if depth > 0 or opens or closes:
            depth = max(depth + opens - closes, 0)
            skip = False
            continue
        if skip:
            skip = False
            continue
        if RE_OPERATOR.match(token) is not None:
            skip = True
            continue
        if token.lower() in _JOINERS:
            skip = True
            continue
        names.add(token.rstrip(',').lower())
    return names


def _system_lines(blocks: Sequence[_Block]) -> list[int]:
    """Return the lines of every ``BuildSystem: meson`` field."""
    return [
        line
        for block in blocks
        for name, _stage, value, line in block.fields
        if RE_BUILD_SYSTEM.match(name) is not None and
        value.strip().lower() == MESON
    ]


def _declared_everywhere(blocks: Sequence[_Block]) -> set[str]:
    """Return every dependency name declared in any build-requires field.

    ``BuildRequires`` is a source-package level field, so RPM merges the
    declarations of every subpackage block into one build dependency set.
    The requirement is therefore satisfied when the name appears anywhere
    in the file, which keeps a subpackage that carries the dependency from
    producing a false finding.
    """
    declared: set[str] = set()
    for block in blocks:
        for name, _stage, value, _line in block.fields:
            if RE_BUILD_REQUIRES.match(name) is not None:
                declared |= _declared_names(value)
    return declared


def _section_list(lines: Sequence[str]) -> list[_Section]:
    """Split the file into sections, keeping each body line's number."""
    found: list[_Section] = []
    name = ''
    suffix = ''
    header = 0
    body: list[tuple[int, str]] = []

    for index, line in enumerate(lines, 1):
        match = RE_SECTION.match(line)
        if match is not None and ('%' + match.group(1)) in KNOWN_SECTIONS:
            if name:
                found.append(_Section(name, suffix, header, body))
            name = '%' + match.group(1)
            suffix = match.group(2).strip()
            header = index
            body = []
            continue
        if not name:
            continue
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        body.append((index, line))

    if name:
        found.append(_Section(name, suffix, header, body))
    return found


def _meson_option(text: str) -> str | None:
    """Return the first meson option argument on a line, or None."""
    match = RE_MESON_OPTION.search(text)
    if match is None:
        return None
    return match.group(1)


def _check_buildrequires(line: int, declared: set[str]) -> list[str]:
    """C1: a meson spec declares meson as a BuildRequires."""
    if REQUIRED_PACKAGE in declared:
        return []
    return [
        f'BuildSystem: {MESON} (line {line}) requires '
        f'"{REQUIRED_PACKAGE}" in BuildRequires; '
        f'missing "{REQUIRED_PACKAGE}"',
    ]


def _misplaced_options(
    blocks: Sequence[_Block], sections: Sequence[_Section],
) -> list[tuple[int, str, str]]:
    """C2: return every meson option that is not in ``BuildOption(conf)``.

    Two shapes are reported. A ``BuildOption`` field whose stage is not
    ``conf`` carries the option in the wrong stage, and a statement inside a
    section body carries it in the wrong place entirely. A section with a
    suffix is skipped: ``%build -a`` and ``%install -a`` exist precisely to
    hold the commands a packager appends after the build system has run, so
    a compiler define there is the packager's own business.
    """
    found: list[tuple[int, str, str]] = []
    for block in blocks:
        for name, stage, value, line in block.fields:
            if RE_BUILD_OPTION.match(name) is None:
                continue
            if stage.lower() == CONF_STAGE:
                continue
            option = _meson_option(value)
            if option is not None:
                found.append((line, f'BuildOption({stage})', option))
    for section in sections:
        if section.suffix:
            continue
        for line, text in section.body:
            option = _meson_option(text)
            if option is not None:
                found.append((line, section.name, option))
    return found


def _plain_managed_sections(
    sections: Sequence[_Section],
) -> list[tuple[int, str]]:
    """C3: return the plain ``%build``/``%install`` sections with a body.

    A section that carries a suffix is the ``-a`` form the page points at,
    which is exactly where the remaining commands belong, so it is never
    reported. A section whose body is empty or holds nothing but comments
    declares nothing of its own and is not reported either.
    """
    return [
        (section.header_line, section.name)
        for section in sections
        if section.name in MANAGED_SECTIONS and not section.suffix and
        section.body
    ]


def _check_spec_build_meson_ext(
    filename: str,
    *,
    check_buildrequires: bool = True,
    check_option_position: bool = True,
    check_plain_sections: bool = True,
) -> list[str]:
    lines, error = _read_lines(filename)
    if error is not None:
        return [error]
    assert lines is not None
    if not (
        check_buildrequires or check_option_position or check_plain_sections
    ):
        return []

    blocks = _blocks_of(lines)
    system_lines = _system_lines(blocks)
    if not system_lines:
        return []

    errors: list[str] = []
    if check_buildrequires:
        declared = _declared_everywhere(blocks)
        errors.extend(_check_buildrequires(system_lines[0], declared))

    sections = _section_list(lines)
    if check_option_position:
        for line, where, option in _misplaced_options(blocks, sections):
            errors.append(
                f'{where} (line {line}) carries the meson option '
                f'"{option}"; meson option arguments belong in '
                f'BuildOption({CONF_STAGE}) for BuildSystem: {MESON}',
            )
    if check_plain_sections:
        for line, name in _plain_managed_sections(sections):
            errors.append(
                f'{name} (line {line}) has a body of its own; '
                f'BuildSystem: {MESON} supplies {name} itself, so the '
                f'extra commands belong in {name} -a',
            )

    return _dedup([f'{filename}: {err}' for err in errors])


def _check_spec_build_meson(filename: str) -> list[str]:
    return _check_spec_build_meson_ext(filename)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description='Check the requirements of a meson build system.',
    )
    parser.add_argument(
        'filenames', nargs='*', help='spec files to check',
    )
    parser.add_argument(
        '--no-check-buildrequires',
        action='store_true',
        help='do not report a missing meson build dependency',
    )
    parser.add_argument(
        '--no-check-option-position',
        action='store_true',
        help='do not report a meson option outside BuildOption(conf)',
    )
    parser.add_argument(
        '--no-check-plain-sections',
        action='store_true',
        help='do not report a %build or %install section with a body',
    )
    args = parser.parse_args(argv)

    ret = 0
    for filename in args.filenames:
        errors = _check_spec_build_meson_ext(
            filename,
            check_buildrequires=not args.no_check_buildrequires,
            check_option_position=not args.no_check_option_position,
            check_plain_sections=not args.no_check_plain_sections,
        )
        if errors:
            ret = 1
            for err in errors:
                print(err)
    return ret
